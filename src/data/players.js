//    FPL Draft Cheat Sheet (draftfantasy.com/fpl/draft-cheat-sheet),
//    pasted in by the user — a real forward-looking xP model built for
//    draft leagues specifically, not last season's history. This is the
//    best-quality `points` value in the pool and takes priority
//    wherever it's available.
//
// For players the cheat sheet doesn't cover, `points` falls back to
// their actual 2025-26 total FPL points (real history, not a
// projection). For players with ~no 2025-26 Premier League history on
// top of that (promoted-club squads, brand-new-to-the-league signings),
// it falls back further to `estimated: true` — a price-derived guess,
// badged EST in the app, since there's no real history or projection to
// draw from.
//
// Re-paste an updated cheat sheet (or any other real projections) to
// refresh `points` as the season develops — see README.

